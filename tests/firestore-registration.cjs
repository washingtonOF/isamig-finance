const {initializeTestEnvironment,assertFails,assertSucceeds}=require('@firebase/rules-unit-testing');
const {doc,setDoc,getDoc,serverTimestamp}=require('firebase/firestore');
const fs=require('node:fs');
(async()=>{
 const env=await initializeTestEnvironment({projectId:'demo-vinnas-registration',firestore:{rules:fs.readFileSync('firestore.rules','utf8')}});
 try{
 const resident=env.authenticatedContext('resident',{email:'resident@example.com',email_verified:true}).firestore();
 const stranger=env.authenticatedContext('stranger',{email:'other@example.com',email_verified:true}).firestore();
 const anonymous=env.unauthenticatedContext().firestore();
 const claim={cpf:'52998224725',phone:'85999990000',whatsapp:true,email:'resident@example.com',createdAt:serverTimestamp()};
 await assertFails(setDoc(doc(anonymous,'registration_claims','resident'),claim));
 await assertFails(setDoc(doc(stranger,'registration_claims','resident'),claim));
 await assertSucceeds(setDoc(doc(resident,'registration_claims','resident'),claim));
 await assertFails(getDoc(doc(stranger,'registration_claims','resident')));
 await assertFails(getDoc(doc(resident,'registration_review_private','resident')));
 await assertFails(setDoc(doc(resident,'registration_decisions','resident'),{decision:'approved',unit:'302'}));
 await assertFails(setDoc(doc(resident,'registration_claims','resident'),claim));
 const master=env.authenticatedContext('master',{email:'washington.s.souza@gmail.com',email_verified:true,firebase:{sign_in_provider:'google.com'}}).firestore();
 await env.withSecurityRulesDisabled(async ctx=>{
  const db=ctx.firestore();
  await setDoc(doc(db,'users','resident'),{email:'resident@example.com',name:'Test',role:'user',status:'pending'});
  await setDoc(doc(db,'registration_review_private','resident'),{result:{status:'matched',unit:'302'}});
  await setDoc(doc(db,'finance_units','302','months','2026-11'),{test:true});
  await setDoc(doc(db,'finance_units','303','months','2026-11'),{test:true});
 });
 await assertSucceeds(getDoc(doc(master,'registration_review_private','resident')));
 await assertFails(setDoc(doc(master,'users','resident'),{unit:'302',role:'resident',status:'approved'},{merge:true}));
 await assertFails(setDoc(doc(master,'registration_decisions','resident'),{decision:'approved',unit:'204',decidedBy:'master',decidedAt:serverTimestamp()}));
 await assertFails(setDoc(doc(master,'registration_decisions','resident'),{decision:'approved',unit:'302',decidedBy:'master',decidedAt:serverTimestamp()}));
 await assertFails(setDoc(doc(master,'users','resident'),{unit:'303',role:'resident',status:'approved'},{merge:true}));
 await assertFails(setDoc(doc(master,'users','resident'),{unit:'302',role:'resident',status:'approved'},{merge:true}));
 await assertFails(getDoc(doc(resident,'finance_units','302','months','2026-11')));
 await env.withSecurityRulesDisabled(async ctx=>{await setDoc(doc(ctx.firestore(),'users','resident'),{unit:'302',role:'resident',status:'approved'},{merge:true});});
 await assertSucceeds(getDoc(doc(resident,'finance_units','302','months','2026-11')));
 await assertFails(getDoc(doc(resident,'finance_units','303','months','2026-11')));
 await assertFails(setDoc(doc(resident,'finance_units','302','months','2026-11'),{test:false}));
 const changed=env.authenticatedContext('resident',{email:'changed@example.com',email_verified:true}).firestore();
 const unverified=env.authenticatedContext('resident',{email:'resident@example.com',email_verified:false}).firestore();
 await assertFails(getDoc(doc(changed,'finance_units','302','months','2026-11')));
 await assertFails(getDoc(doc(unverified,'finance_units','302','months','2026-11')));
 await assertFails(getDoc(doc(anonymous,'finance_units','302','months','2026-11')));
 await assertFails(setDoc(doc(resident,'users','resident'),{role:'administrative'},{merge:true}));
 await assertFails(setDoc(doc(master,'users','resident'),{unit:'101',role:'administrative'},{merge:true}));
 await assertFails(setDoc(doc(master,'test_access','resident'),{unit:'107',status:'approved',updatedBy:'master',updatedAt:serverTimestamp()}));
 await assertFails(getDoc(doc(resident,'registration_auth_inventory','resident')));
 await assertSucceeds(setDoc(doc(master,'users','resident'),{status:'revoked'},{merge:true}));
 await assertFails(getDoc(doc(resident,'finance_units','302','months','2026-11')));
 console.log('Registration security checks passed');
 }finally{await env.cleanup();}
})().catch(e=>{console.error(e);process.exitCode=1});
